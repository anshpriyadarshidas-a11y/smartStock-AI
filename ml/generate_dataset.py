# Global holiday lift applied when Holiday_Flag == 1.
HOLIDAY_LIFT = 1.25

SEASONS = list({"Winter", "Spring", "Summer", "Monsoon", "Autumn"})


def season_for_month(month: int) -> str:
    """Map a calendar month (1-12) to a business season."""
    if month in (12, 1, 2):
        return "Winter"
    if month in (3, 4, 5):
        return "Summer"
    if month in (6, 7, 8, 9):
        return "Monsoon"
    return "Autumn"  # Oct / Nov


def month_is_holiday(month: int, rng: np.random.Generator) -> int:
    """Flag heavy-holiday months (festive/New Year) and random peaks."""
    if month in (11, 12, 1):  # Diwali, Christmas, New Year
        return 1
    return int(rng.random() < 0.25)


class SyntheticDataGenerator:
    """Generate a realistic monthly inventory snapshot dataset."""

    def __init__(self, n_products: int = 250, n_months: int = 25, seed: int = 42) -> None:
        self.n_products = n_products
        self.n_months = n_months
        self.rng = np.random.default_rng(seed)

    # ------------------------------------------------------------------ #
    # Internal generation helpers
    # ------------------------------------------------------------------ #
    def _monthly_dates(self, end_month: Tuple[int, int]) -> List[date]:
        """Return the first day of each of the last ``n_months`` months."""
        year, month = end_month
        dates: List[date] = []
        for _ in range(self.n_months):
            dates.append(date(year, month, 1))
            month -= 1
            if month == 0:
                month = 12
                year -= 1
        return list(reversed(dates))

    def _next_period_demand(self, units_sold: float, trend: float) -> float:
        """Project next month's demand from this month's sales + trend."""
        trend_effect = (trend - 50) / 50 * 0.30  # +-30%
        return units_sold * max(0.6, min(1.5, 1.0 + trend_effect))

    def _reorder_policy(self, current_stock: float, minimum_stock: float,
                        expected_next: float, lead_time: int) -> int:
        """Business rule that produces the supervised target label.

        A reorder point of ``minimum_stock + 50% of expected demand`` means we
        order only when the projected stock-at-delivery would fall below the
        safety threshold. Ordering raises stock back up to ``expected_next``.
        """
        reorder_point = minimum_stock + 0.5 * expected_next
        if current_stock >= reorder_point:
            return 0
        target_level = max(minimum_stock, expected_next)
        return int(math.ceil(max(0.0, target_level - current_stock)))

    # ------------------------------------------------------------------ #
    # Public API
    # ------------------------------------------------------------------ #
    def generate(self) -> pd.DataFrame:
        """Build the full synthetic dataset as a DataFrame."""
        category_names = list(CATEGORIES.keys())
        end_month = (2026, 8)
        dates = self._monthly_dates(end_month)
        rows: List[Dict] = []

        LOG.info("Generating %d products x %d months ...", self.n_products, self.n_months)

        for product_idx in range(1, self.n_products + 1):
            category = category_names[product_idx % len(CATEGORIES)]
            cfg = CATEGORIES[category]

            product_id = f"PROD-{product_idx:04d}"
            product_name = f"{category} {cfg.name_parts[product_idx % len(cfg.name_parts)]}"
            price = round(self.rng.uniform(cfg.price_min, cfg.price_max), 2)
            lead_time = int(self.rng.integers(cfg.lead_time_min, cfg.lead_time_max + 1))
            base_demand = float(self.rng.uniform(cfg.base_min, cfg.base_max))

            # Market trend follows a per-product random walk with category drift.
            trend = float(self.rng.uniform(35, 65))
            trend_drift = self.rng.uniform(-2.5, 2.5)

            # Simulated inventory state carried across months. We start with a
            # healthy stock level and model the lead time: orders placed in
            # month M arrive ~lead_time days later (-> month M+1 here).
            current_stock = base_demand * self.rng.uniform(1.5, 2.5)
            minimum_stock = round(0.2 * base_demand)
            pending_arrivals: Dict[int, float] = {}

            for date_index, snapshot_date in enumerate(dates):
                # Deliver any orders that are due this month.
                current_stock += pending_arrivals.pop(date_index, 0.0)
                season = season_for_month(snapshot_date.month)
                holiday = month_is_holiday(snapshot_date.month, self.rng)

                # Weather score: seasonal base + noise (0=extreme, 100=perfect).
                seasonal_weather = {1: 45, 2: 50, 3: 70, 4: 75, 5: 80, 6: 85,
                                    7: 80, 8: 70, 9: 60, 10: 65, 11: 55, 12: 45}
                weather = float(self.rng.normal(seasonal_weather[snapshot_date.month], 12))
                weather = max(5.0, min(100.0, weather))

                trend = max(5.0, min(100.0, trend + self.rng.normal(trend_drift, 4)))
                trend_effect = (trend - 50) / 50 * 0.35  # +-35%

                # Price elasticity: expensive items sell slightly slower.
                price_effect = 1.0 - 0.15 * ((price - cfg.price_min) / max(cfg.price_max - cfg.price_min, 1) - 0.5)

                seasonal_mult = cfg.seasonal[season]
                weather_effect = (weather - 50) / 50 * 0.20  # +-20%
                noise = self.rng.uniform(0.75, 1.25)

                units_sold = base_demand * seasonal_mult * (1 + trend_effect) \
                    * (1 + (holiday * (HOLIDAY_LIFT - 1))) * (1 + weather_effect) \
                    * price_effect * noise
                units_sold = max(0.0, round(units_sold))

                expected_next = self._next_period_demand(units_sold, trend)
                reorder_qty = self._reorder_policy(current_stock, minimum_stock,
                                                   expected_next, lead_time)

                rows.append({
                    "Product_ID": product_id,
                    "Product_Name": product_name,
                    "Category": category,
                    "Date": snapshot_date.strftime("%Y-%m-%d"),
                    "Current_Stock": round(max(0.0, current_stock)),
                    "Minimum_Stock": minimum_stock,
                    "Units_Sold": units_sold,
                    "Price": price,
                    "Supplier_Lead_Time": lead_time,
                    "Market_Trend_Score": round(trend, 1),
                    "Season": season,
                    "Holiday_Flag": holiday,
                    "Weather_Score": round(weather, 1),
                    "Reorder_Quantity": reorder_qty,
                })

                # Simulate the month: record the pending delivery and consume
                # stock from sales. Sales that can't be covered = stock-out.
                arrival_idx = date_index + max(1, math.ceil(lead_time / 30))
                if reorder_qty > 0:
                    pending_arrivals[arrival_idx] = pending_arrivals.get(arrival_idx, 0.0) + reorder_qty
                current_stock = max(0.0, current_stock - units_sold)

        df = pd.DataFrame(rows)
        self._inject_missing(df)
        self._inject_outliers(df)
        return df

    # ------------------------------------------------------------------ #
    # Data-quality injections (missing values + outliers)
    # ------------------------------------------------------------------ #
    def _inject_missing(self, df: pd.DataFrame) -> None:
        """Replace ~1% of values in selected columns with NaN."""
        LOG.info("Injecting missing values (~1%% per column) ...")
        for column in ("Market_Trend_Score", "Weather_Score", "Price", "Current_Stock",
                       "Supplier_Lead_Time"):
            mask = self.rng.random(len(df)) < 0.01
            df.loc[mask, column] = np.nan

    def _inject_outliers(self, df: pd.DataFrame) -> None:
        """Add a handful of extreme sales records to stress-test the models."""
        LOG.info("Injecting 5 outliers into Units_Sold ...")
        outlier_rows = self.rng.choice(len(df), size=5, replace=False)
        df.loc[outlier_rows, "Units_Sold"] = df.loc[outlier_rows, "Units_Sold"] * 6.0

    def save(self, df: pd.DataFrame, output_path: Path = DEFAULT_DATASET_PATH) -> Path:
        """Persist the generated dataset to CSV and return the path."""
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(output_path, index=False)
        LOG.info("Dataset written -> %s (%d rows)", output_path, len(df))
        return output_path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate the SmartStock AI dataset.")
    parser.add_argument("--products", type=int, default=250, help="Number of products")
    parser.add_argument("--months", type=int, default=25, help="Months of history per product")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    parser.add_argument("--output", type=str, default=str(DEFAULT_DATASET_PATH),
                        help="Output CSV path")
    return parser.parse_args()


