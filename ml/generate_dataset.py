"""Generate a realistic synthetic inventory dataset for SmartStock AI.

Creates a CSV with at least 5000 records (default: 6250 rows = 250 products
x 25 months) that mimics a small business's monthly inventory snapshots.

The ``Reorder_Quantity`` target is generated by a deterministic restocking
policy, which makes the forecasting problem learnable:

    expected_next_demand = units_sold x (1 + trend_effect)
    reorder_quantity     = max(0, ceil(max(minimum_stock, expected_next_demand)
                                       - current_stock))

A small amount of missing data and outliers is injected so the downstream
preprocessing steps (missing-value handling) are exercised for real.

Usage:
    python generate_dataset.py
    python generate_dataset.py --products 300 --months 24 --seed 42
"""
